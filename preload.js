const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('tcg', {
  homeStats: () => ipcRenderer.invoke('home:stats'),
  listCollections: (tcg, opts) => ipcRenderer.invoke('collections:list', tcg, opts),
  getCollection: (id, opts) => ipcRenderer.invoke('collection:get', id, opts),
  saveCustomCollection: (draft) => ipcRenderer.invoke('custom:save', draft),
  deleteCustomCollection: (id) => ipcRenderer.invoke('custom:delete', id),
  getNotes:(id) => ipcRenderer.invoke('notes:get', id),
  setCollectionNotes: (id, notes) => ipcRenderer.invoke('collection:setNotes', id, notes),
  setOwned: (cardId, quantity, card) => ipcRenderer.invoke('card:setOwned', cardId, quantity, card),
  setVariantOwned: (cardId, variant, quantity, card) => ipcRenderer.invoke('card:setVariant', cardId, variant, quantity, card),
  searchCards: (name, tcg) => ipcRenderer.invoke('cards:search', name, tcg),
  getPrintings: (card) => ipcRenderer.invoke('card:printings', card),
  getPrices: (card) => ipcRenderer.invoke('card:prices', card),
  setHidden: (collectionId, cardId, hidden) => ipcRenderer.invoke('card:setHidden', collectionId, cardId, hidden),
  openTcgCollector: (card) => ipcRenderer.invoke('card:openTcgCollector', card),
  openTcgplayer: (card) => ipcRenderer.invoke('card:openTcgplayer', card),
  openScryfall: (card) => ipcRenderer.invoke('card:openScryfall', card),
  openMoxfield: (card) => ipcRenderer.invoke('card:openMoxfield', card),
  chooseExportPath: (opts) => ipcRenderer.invoke('export:choosePath', opts),
  exportCollection: (opts) => ipcRenderer.invoke('collection:export', opts),
  copyExport: (opts) => ipcRenderer.invoke('collection:copyExport', opts),
  revealFile: (filePath) => ipcRenderer.invoke('file:reveal', filePath),
  listDecks: () => ipcRenderer.invoke('decks:list'),
  getDeck: (id) => ipcRenderer.invoke('deck:get', id),
  createDeck: (draft) => ipcRenderer.invoke('deck:create', draft),
  updateDeck: (id, changes) => ipcRenderer.invoke('deck:update', id, changes),
  deleteDeck: (id) => ipcRenderer.invoke('deck:delete', id),
  addDeckCard: (deckId, card, opts) => ipcRenderer.invoke('deck:addCard', deckId, card, opts),
  updateDeckCard: (deckId, cardId, changes) => ipcRenderer.invoke('deck:updateCard', deckId, cardId, changes),
  wishlistIds: () => ipcRenderer.invoke('wishlist:ids'),
  getWishlist: (tcg) => ipcRenderer.invoke('wishlist:get', tcg),
  addToWishlist: (tcg, card) => ipcRenderer.invoke('wishlist:add', tcg, card),
  removeFromWishlist: (cardId) => ipcRenderer.invoke('wishlist:remove', cardId),
  pokedexStats: (kinds) => ipcRenderer.invoke('pokedex:stats', kinds),
  getPokedex: (opts) => ipcRenderer.invoke('pokedex:get', opts),
  getPokemon: (dexId, kinds) => ipcRenderer.invoke('pokedex:pokemon', dexId, kinds),
});
